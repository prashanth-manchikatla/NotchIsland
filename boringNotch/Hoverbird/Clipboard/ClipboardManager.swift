//
//  ClipboardManager.swift
//  Hoverbird
//
//  Clipboard history ("stack"): text, links, colours, images and files.
//  • Polls only NSPasteboard.changeCount (a cheap integer) once a second; the
//    clipboard contents are read only when that number changes.
//  • Skips password managers and anything marked concealed/transient.
//  • Images are stored on disk; only small thumbnails live in memory.
//

import AppKit
import Combine
import CryptoKit
import Defaults
import ImageIO
import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, image, file, color }

    let id: UUID
    var kind: Kind
    var text: String?
    var imageFile: String?
    var fingerprint: String
    var sourceBundleID: String?
    var date: Date
    var pinned: Bool

    var fileURLs: [URL] {
        guard kind == .file, let text else { return [] }
        return text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
    }
}

@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var lastCopiedID: UUID?

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var ownChangeCount: Int?
    private var timer: Timer?
    private var saveTask: Task<Void, Never>?
    private var keyMonitor: Any?
    private var lastCommandC: Date = .distantPast
    private var cancellables = Set<AnyCancellable>()
    private let thumbnailCache = NSCache<NSString, NSImage>()

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    private var storeURL: URL { IslandPaths.appSupport.appendingPathComponent("clipboard.json") }
    private var imageDir: URL {
        let dir = IslandPaths.appSupport.appendingPathComponent("ClipboardImages", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    private init() {
        thumbnailCache.countLimit = 40
        load()
        Defaults.publisher(.clipboardEnabled)
            .receive(on: RunLoop.main)
            .sink { [weak self] change in
                if change.newValue { self?.start() } else { self?.stop() }
            }
            .store(in: &cancellables)
        Defaults.publisher(.clipboardDoubleCopyOpens)
            .combineLatest(NotificationCenter.default.publisher(for: .accessibilityAuthorizationChanged).map { _ in () }.prepend(()))
            .receive(on: RunLoop.main)
            .sink { [weak self] _ in self?.updateKeyMonitor() }
            .store(in: &cancellables)
    }

    // MARK: - Monitoring

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.4
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if let own = ownChangeCount, own == count { return }
        capture(from: pb)
    }

    private func capture(from pb: NSPasteboard) {
        let types = Set((pb.types ?? []).map(\.rawValue))
        if Defaults[.clipboardIgnoreConcealed], !types.isDisjoint(with: Self.skipTypes) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Defaults[.clipboardIgnoredApps].contains(source) { return }

        var newItem: ClipItem?

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let joined = urls.map(\.path).joined(separator: "\n")
            newItem = ClipItem(id: UUID(), kind: .file, text: joined, imageFile: nil,
                               fingerprint: "f:" + Self.hash(joined), sourceBundleID: source, date: Date(), pinned: false)
        } else if let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            var text = String(string.prefix(200_000))
            // Copied a link with tracking junk: put the clean link on the clipboard instead.
            if Defaults[.clipboardCleanLinks], let cleaned = LinkCleaner.clean(text) {
                pb.clearContents()
                pb.setString(cleaned, forType: .string)
                ownChangeCount = pb.changeCount
                lastChangeCount = pb.changeCount
                text = cleaned
            }
            let kind = Self.classify(text)
            newItem = ClipItem(id: UUID(), kind: kind, text: text, imageFile: nil,
                               fingerprint: "t:" + Self.hash(text), sourceBundleID: source, date: Date(), pinned: false)
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            let fingerprint = "i:" + Self.hash(data)
            if let existing = items.firstIndex(where: { $0.fingerprint == fingerprint }) {
                bump(existing)
                return
            }
            let name = UUID().uuidString + ".png"
            let png: Data? = pb.data(forType: .png) ?? NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            guard let png, (try? png.write(to: imageDir.appendingPathComponent(name))) != nil else { return }
            newItem = ClipItem(id: UUID(), kind: .image, text: nil, imageFile: name,
                               fingerprint: fingerprint, sourceBundleID: source, date: Date(), pinned: false)
        }

        guard let newItem else { return }
        if let existing = items.firstIndex(where: { $0.fingerprint == newItem.fingerprint }) {
            bump(existing)
            return
        }
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) {
            items.insert(newItem, at: 0)
        }
        prune()
        scheduleSave()
        if Defaults[.clipboardShowCopyPill] {
            IslandActivityHub.shared.showPill(.copied(preview(for: newItem)), duration: 1.4)
        }
    }

    private func bump(_ index: Int) {
        var item = items.remove(at: index)
        item.date = Date()
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) {
            items.insert(item, at: 0)
        }
        scheduleSave()
    }

    // MARK: - Actions

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text, .link, .color:
            pb.setString(item.text ?? "", forType: .string)
        case .file:
            pb.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let file = item.imageFile, let data = try? Data(contentsOf: imageDir.appendingPathComponent(file)) {
                pb.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        }
        ownChangeCount = pb.changeCount
        lastChangeCount = pb.changeCount
        lastCopiedID = item.id
        if let index = items.firstIndex(of: item), index != 0 { bump(index) }
    }

    /// Copies, closes the island and pastes into the frontmost app (needs Accessibility).
    func paste(_ item: ClipItem) {
        copy(item)
        guard AXIsProcessTrusted() else { return }
        NotificationCenter.default.post(name: .islandCloseAll, object: nil)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }

    func select(_ item: ClipItem) {
        if Defaults[.clipboardPasteOnSelect] { paste(item) } else { copy(item) }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(of: item) else { return }
        items[index].pinned.toggle()
        scheduleSave()
    }

    func delete(_ item: ClipItem) {
        withAnimation(.spring(response: 0.3, dampingFraction: 0.85)) {
            items.removeAll { $0.id == item.id }
        }
        removeImage(of: item)
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        let removed = items.filter { !keepPinned || !$0.pinned }
        removed.forEach(removeImage)
        withAnimation { items.removeAll { !keepPinned || !$0.pinned } }
        scheduleSave()
    }

    // MARK: - Presentation helpers

    func preview(for item: ClipItem) -> String {
        switch item.kind {
        case .image: return "Image"
        case .file:
            let urls = item.fileURLs
            return urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) files"
        default:
            return (item.text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ")
        }
    }

    func thumbnail(for item: ClipItem, maxPixel: CGFloat = 260) -> NSImage? {
        guard item.kind == .image, let file = item.imageFile else { return nil }
        if let cached = thumbnailCache.object(forKey: file as NSString) { return cached }
        let url = imageDir.appendingPathComponent(file)
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixel,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
        thumbnailCache.setObject(image, forKey: file as NSString)
        return image
    }

    static func color(from text: String?) -> Color? {
        guard var hex = text?.trimmingCharacters(in: .whitespacesAndNewlines) else { return nil }
        if hex.hasPrefix("#") { hex.removeFirst() }
        guard hex.count == 6, let value = UInt32(hex, radix: 16) else { return nil }
        return Color(red: Double((value >> 16) & 0xFF) / 255, green: Double((value >> 8) & 0xFF) / 255,
                     blue: Double(value & 0xFF) / 255)
    }

    // MARK: - Double ⌘C opens the history

    private func updateKeyMonitor() {
        let wanted = Defaults[.clipboardDoubleCopyOpens] && AXIsProcessTrusted()
        if wanted, keyMonitor == nil {
            keyMonitor = NSEvent.addGlobalMonitorForEvents(matching: .keyDown) { event in
                guard event.keyCode == 8, // "c"
                      event.modifierFlags.intersection(.deviceIndependentFlagsMask) == .command,
                      !event.isARepeat else { return }
                MainActor.assumeIsolated {
                    let manager = ClipboardManager.shared
                    let now = Date()
                    if now.timeIntervalSince(manager.lastCommandC) < 0.45 {
                        manager.lastCommandC = .distantPast
                        NotificationCenter.default.post(name: .islandOpenTab, object: NotchViews.clipboard)
                    } else {
                        manager.lastCommandC = now
                    }
                }
            }
        } else if !wanted, let keyMonitor {
            NSEvent.removeMonitor(keyMonitor)
            self.keyMonitor = nil
        }
    }

    // MARK: - Persistence

    private func prune() {
        let limit = max(10, Defaults[.clipboardHistoryLimit])
        var unpinnedSeen = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.pinned { kept.append(item); continue }
            unpinnedSeen += 1
            if unpinnedSeen <= limit { kept.append(item) } else { removeImage(of: item) }
        }
        if kept.count != items.count { items = kept }
    }

    private func removeImage(of item: ClipItem) {
        guard let file = item.imageFile else { return }
        try? FileManager.default.removeItem(at: imageDir.appendingPathComponent(file))
        thumbnailCache.removeObject(forKey: file as NSString)
    }

    private func scheduleSave() {
        saveTask?.cancel()
        let snapshot = items
        let url = storeURL
        saveTask = Task.detached(priority: .utility) {
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled else { return }
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: url, options: .atomic)
            }
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: storeURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private static func classify(_ text: String) -> ClipItem.Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.range(of: #"^#?[0-9A-Fa-f]{6}$"#, options: .regularExpression) != nil { return .color }
        if !trimmed.contains(" "), !trimmed.contains("\n"),
           let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
           ["http", "https", "mailto", "ftp"].contains(scheme) {
            return .link
        }
        return .text
    }

    private static func hash(_ string: String) -> String { hash(Data(string.utf8)) }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
    }
}
